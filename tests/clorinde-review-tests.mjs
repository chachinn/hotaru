import assert from 'node:assert/strict';
import fs from 'node:fs';
import { RELEASED_AVATAR_AUDIT_V45 } from './fixtures/released-avatar-audit-v45.mjs';
import { reviewedBuildProfile } from '../js/data/build-profiles/index.js';
import { inferBuildProfile, statTargets } from '../js/features/build-engine.js';
import { resolveBuildProfile } from '../js/features/build-profiles.js';
import { CLORINDE_REVIEWED_TEAMS } from '../js/data/team-profiles/clorinde-reviewed.js';
import { registerReviewedTeams } from '../js/data/team-profiles/index.js';
import { recommendedTeamsForCharacter, teamHasValidSource } from '../js/data/team-recommendations.js';
import { CLORINDE_COMPATIBILITY_POLICY, clorindeCompatibilityForCharacter, auditClorindeCompatibility } from '../js/data/character-compatibility/clorinde.js';
import { matchReviewedTeams } from '../js/features/roster-team-matcher.js';
import { artifactFarmInfo, weaponFarmInfo } from '../js/data/equipment-farm-registry.js';

registerReviewedTeams(CLORINDE_REVIEWED_TEAMS);
const fallback=inferBuildProfile({name:'Clorinde',element:'Electro',weapon:'Sword',description:'Electro on-field Bond of Life damage dealer'});
const profile=resolveBuildProfile({name:'Clorinde',element:'Electro'},fallback,{});
assert.equal(profile.profileSource,'reviewed');
assert.equal(profile.role,'On-field Electro Main DPS');
assert.equal(profile.roleGroup,'Main DPS');
assert.equal(profile.scaling,'ATK');
assert.deepEqual(profile.tierRatings,[{label:'Main DPS',rating:'A'},{label:'Sub-DPS',rating:'—'},{label:'Support',rating:'—'},{label:'Exploration',rating:'S'}]);
assert.deepEqual(profile.voiceActors,[{label:'EN',name:'Crystal Lee'},{label:'JP',name:'Ishikawa Yui (石川由依)'},{label:'CN',name:'Zhao Hanyu (赵涵雨)'},{label:'KR',name:'Shin Na-ri (신나리)'}]);
assert.equal(profile.activeVariant?.id,'standard-electro');
assert.deepEqual(profile.mainStats.sands,['ATK%']);
assert.deepEqual(profile.mainStats.goblet,['Electro DMG%']);
assert.deepEqual(profile.talentPriority,['skill','burst','attack']);
assert.equal(profile.weaponPriority[0],'Absolution');
assert.equal(profile.artifactPriority[0],'Fragment of Harmonic Whimsy');
assert.equal(statTargets(profile,{burstCycle:'everyOther',sameElement:0,favonius:0}).er.good,120);
assert.equal(statTargets(profile,{burstCycle:'every',sameElement:0,favonius:0}).er.good,210);
assert.equal(statTargets(profile,{burstCycle:'every',sameElement:1,favonius:0}).er.good,130);
const raw=reviewedBuildProfile('Clorinde');
assert.equal(raw.variants.length,4,'Clorinde must retain all four meaningfully distinct reviewed build variants');
assert.deepEqual(raw.variants.map(v=>v.id),['standard-electro','aggravate','thundering-fury-quicken','quickbloom-quickburn']);
const aggravate=resolveBuildProfile({name:'Clorinde'},fallback,{buildVariant:'aggravate'});
assert.deepEqual(aggravate.mainStats.sands,['ATK%','Elemental Mastery']);
assert.equal(aggravate.reactionDriven,true);
const tf=resolveBuildProfile({name:'Clorinde'},fallback,{buildVariant:'thundering-fury-quicken'});
assert.equal(tf.artifactPriority[0],'Thundering Fury');
const reaction=resolveBuildProfile({name:'Clorinde'},fallback,{buildVariant:'quickbloom-quickburn'});
assert.equal(reaction.reactionDriven,true);
assert.deepEqual(reaction.mainStats.sands,['ATK%','Elemental Mastery']);
assert.equal(weaponFarmInfo('Absolution').kind,'Limited 5-star signature Sword');
assert.match(weaponFarmInfo('Finale of the Deep').source,/Forge/i);
assert.match(artifactFarmInfo('Thundering Fury').source,/Midsummer Courtyard/i);

const sourced=recommendedTeamsForCharacter('Clorinde').filter(teamHasValidSource);
const unique=new Set(sourced.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
assert.ok(unique.size>=30,`Clorinde must expose at least 30 genuinely distinct sourced/source-informed compositions when evidence supports them; got ${unique.size}`);
assert.equal(unique.size,CLORINDE_REVIEWED_TEAMS.length,'reviewed Clorinde team library should not inflate counts through duplicate member sets');
assert.ok(CLORINDE_REVIEWED_TEAMS.every(team=>team.source?.url&&/^https?:\/\//.test(team.source.url)));
assert.ok(CLORINDE_REVIEWED_TEAMS.every(team=>['exact','adapted'].includes(team.provenance)));
const audit=auditClorindeCompatibility(RELEASED_AVATAR_AUDIT_V45);
assert.equal(audit.total,148,'Clorinde compatibility audit must cover every released avatar record');
assert.ok(audit.rows.every(row=>row.status!=='invalid'));
assert.ok(audit.rows.every(row=>row.status!=='unverified'||(!row.smartTeamApproved&&!row.adaptationAllowed)));
for(const name of ['Fischl','Nahida','Chevreuse','Furina','Columbina','Ineffa','Xilonen'])assert.equal(clorindeCompatibilityForCharacter(name).smartTeamApproved,true,`${name} must be source-backed for Clorinde`);
assert.equal(clorindeCompatibilityForCharacter('Sethos').adaptationAllowed,false,'field-time-conflicting Electro carries must not be inferred as compatible');
assert.equal(clorindeCompatibilityForCharacter('Aether TPS').status,'not-applicable');

const ownedRoster=[{name:'Clorinde',level:90,status:'Finished',priority:'High'},{name:'Fischl',level:90,status:'Finished',priority:'High'},{name:'Nahida',level:90,status:'Finished',priority:'High'},{name:'Kaedehara Kazuha',level:90,status:'Finished',priority:'High'},{name:'Chevreuse',level:90,status:'Usable',priority:'High'},{name:'Thoma',level:90,status:'Usable',priority:'High'}];
const owned=matchReviewedTeams({roster:ownedRoster,lockedNames:['Clorinde'],allowUnowned:false,limit:'all'});
assert.ok(owned.results.length>0);
assert.ok(owned.results.every(team=>team.ownedComplete&&team.missing.length===0),'Owned-only must never leak an unowned teammate');
const preview=matchReviewedTeams({roster:[{name:'Clorinde',level:90}],lockedNames:['Clorinde'],allowUnowned:true,limit:'all'});
assert.ok(preview.results.some(team=>team.missing.length>0));
for(const reactionName of ['aggravate','quickbloom','overload','electro-charged','lunar-charged','hypercarry']){
  const result=matchReviewedTeams({roster:[{name:'Clorinde',level:90}],lockedNames:['Clorinde'],allowUnowned:true,limit:'all',reaction:reactionName});
  assert.ok(result.results.length>0,`Clorinde ${reactionName} filter must retain reviewed teams`);
}

