import assert from 'node:assert/strict';
import fs from 'node:fs';
import { RELEASED_AVATAR_AUDIT_V45 } from './fixtures/released-avatar-audit-v45.mjs';
import { reviewedBuildProfile } from '../js/data/build-profiles/index.js';
import { inferBuildProfile } from '../js/features/build-engine.js';
import { resolveBuildProfile } from '../js/features/build-profiles.js';
import { COLUMBINA_REVIEWED_TEAMS } from '../js/data/team-profiles/columbina-reviewed.js';
import { registerReviewedTeams } from '../js/data/team-profiles/index.js';
import { recommendedTeamsForCharacter, teamHasValidSource } from '../js/data/team-recommendations.js';
import { COLUMBINA_COMPATIBILITY_POLICY, columbinaCompatibilityForCharacter, auditColumbinaCompatibility } from '../js/data/character-compatibility/columbina.js';
import { matchReviewedTeams } from '../js/features/roster-team-matcher.js';
import { artifactFarmInfo, weaponFarmInfo } from '../js/data/equipment-farm-registry.js';

registerReviewedTeams(COLUMBINA_REVIEWED_TEAMS);
const fallback=inferBuildProfile({name:'Columbina',element:'Hydro',weapon:'Catalyst',description:'Hydro support and Lunar reaction enabler'});
const profile=resolveBuildProfile({name:'Columbina',element:'Hydro'},fallback,{});
assert.equal(profile.profileSource,'reviewed');
assert.equal(profile.role,'Off-field Support / DPS');
assert.equal(profile.roleGroup,'Support');
assert.equal(profile.scaling,'HP');
assert.deepEqual(profile.tierRatings,[{label:'Main DPS',rating:'—'},{label:'Sub-DPS',rating:'SS'},{label:'Support',rating:'SS'},{label:'Exploration',rating:'B'}]);
assert.deepEqual(profile.voiceActors,[{label:'EN',name:'Emi Lo'},{label:'JP',name:'Lynn'},{label:'CN',name:'Yang Menglu (杨梦露)'},{label:'KR',name:'Yu Yeong (유영)'}]);
assert.equal(profile.activeVariant?.id,'offfield');
assert.deepEqual(profile.mainStats.sands,['HP%','Energy Recharge']);
assert.deepEqual(profile.mainStats.goblet,['HP%']);
assert.deepEqual(profile.talentPriority,['skill','burst','attack']);
assert.equal(profile.weaponPriority[0],"Nocturne's Curtain Call");
assert.equal(profile.artifactPriority[0],"Silken Moon's Serenade");
assert.ok(profile.goalStats.some(row=>row.label==='HP'&&/35,000/.test(row.value)));
assert.ok(profile.goalStats.some(row=>row.label==='Energy Recharge'&&/KQM/.test(row.value)));
const raw=reviewedBuildProfile('Columbina');
assert.equal(raw.variants.length,2,'Columbina should expose only the two legitimate reviewed build variants');
assert.deepEqual(raw.variants.map(v=>v.id),['offfield','onfield'],'existing build-context ids must remain backward compatible');
const reaction=resolveBuildProfile({name:'Columbina'},fallback,{buildVariant:'onfield'});
assert.equal(reaction.role,'On-field Lunar-Bloom DPS');
assert.equal(reaction.roleGroup,'DPS');
assert.deepEqual(reaction.mainStats.goblet,['Hydro DMG%','HP%']);
assert.equal(reaction.artifactPriority[0],'Aubade of Morningstar and Moon');
assert.equal(reaction.artifactPriority[1],"Night of the Sky's Unveiling");
assert.equal(weaponFarmInfo("Nocturne's Curtain Call").kind,'Limited 5-star signature Catalyst');
assert.match(weaponFarmInfo('Prototype Amber').source,/Forge/i);
assert.equal(artifactFarmInfo("Silken Moon's Serenade").source,'Frostladen Machinery');

const sourced=recommendedTeamsForCharacter('Columbina').filter(teamHasValidSource);
const unique=new Set(sourced.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
assert.ok(unique.size>=30,`Columbina must expose 30+ distinct sourced/source-informed reviewed compositions; got ${unique.size}`);
assert.ok(COLUMBINA_REVIEWED_TEAMS.every(team=>team.source?.url&&/^https?:\/\//.test(team.source.url)));
assert.ok(COLUMBINA_REVIEWED_TEAMS.every(team=>['exact','adapted'].includes(team.provenance)));
const audit=auditColumbinaCompatibility(RELEASED_AVATAR_AUDIT_V45);
assert.equal(audit.total,148,'Columbina compatibility audit must cover every released avatar record');
assert.ok(audit.rows.every(row=>row.status!=='invalid'));
assert.ok(audit.rows.every(row=>row.status!=='unverified'||(!row.smartTeamApproved&&!row.adaptationAllowed)));
assert.equal(columbinaCompatibilityForCharacter('Flins').smartTeamApproved,true);
assert.equal(columbinaCompatibilityForCharacter('Nefer').smartTeamApproved,true);
assert.equal(columbinaCompatibilityForCharacter('Zibai').smartTeamApproved,true);
assert.equal(columbinaCompatibilityForCharacter('Alhaitham').adaptationAllowed,false,'unsupported generic Dendro pairing must remain blocked unless explicitly sourced');
assert.equal(columbinaCompatibilityForCharacter('Aether TPS').status,'not-applicable');

const ownedRoster=[{name:'Columbina',level:90,status:'Finished',priority:'High'},{name:'Flins',level:90,status:'Finished',priority:'High'},{name:'Ineffa',level:90,status:'Finished',priority:'High'},{name:'Sucrose',level:90,status:'Finished',priority:'High'},{name:'Lauma',level:90,status:'Usable',priority:'High'},{name:'Nefer',level:90,status:'Usable',priority:'High'},{name:'Nahida',level:90,status:'Finished',priority:'High'}];
const owned=matchReviewedTeams({roster:ownedRoster,lockedNames:['Columbina'],allowUnowned:false,limit:'all'});
assert.ok(owned.results.length>0);
assert.ok(owned.results.every(team=>team.ownedComplete&&team.missing.length===0),'Owned-only must never leak an unowned teammate');
const preview=matchReviewedTeams({roster:[{name:'Columbina',level:90}],lockedNames:['Columbina'],allowUnowned:true,limit:'all'});
assert.ok(preview.results.some(team=>team.missing.length>0));
for(const reactionName of ['lunar-charged','lunar-bloom','lunar-crystallize']){
  const result=matchReviewedTeams({roster:[{name:'Columbina',level:90}],lockedNames:['Columbina'],allowUnowned:true,limit:'all',reaction:reactionName});
  assert.ok(result.results.length>0,`Columbina ${reactionName} filter must retain reviewed teams`);
}
const game8Ui=fs.readFileSync(new URL('../js/features/game8-guide-ui.js',import.meta.url),'utf8');
assert.match(game8Ui,/data-hotaru-build-prev/);
assert.match(game8Ui,/data-hotaru-build-next/);
assert.match(game8Ui,/preventScroll:true/,'build arrows must not jump the user back up the character page');
assert.match(game8Ui,/legacyVariants\.remove/,'the old separate Build Variants card must be removed for reviewed characters');
assert.match(game8Ui,/data-hotaru-build-carousel/,'all reviewed characters must use the in-place build carousel');
assert.match(COLUMBINA_COMPATIBILITY_POLICY.rule,/Every released avatar record/);
console.log(`Columbina review QA passed · ${unique.size} unique sourced teams · ${audit.total}/148 compatibility records checked · in-place build carousel enabled.`);
