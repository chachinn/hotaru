import assert from 'node:assert/strict';
import { RELEASED_AVATAR_AUDIT_V45 } from './fixtures/released-avatar-audit-v45.mjs';
import { reviewedBuildProfile } from '../js/data/build-profiles/index.js';
import { inferBuildProfile } from '../js/features/build-engine.js';
import { resolveBuildProfile } from '../js/features/build-profiles.js';
import { CHASCA_REVIEWED_TEAMS } from '../js/data/team-profiles/chasca-reviewed.js';
import { registerReviewedTeams } from '../js/data/team-profiles/index.js';
import { recommendedTeamsForCharacter, teamHasValidSource } from '../js/data/team-recommendations.js';
import { CHASCA_COMPATIBILITY_POLICY, chascaCompatibilityForCharacter, auditChascaCompatibility } from '../js/data/character-compatibility/chasca.js';
import { matchReviewedTeams } from '../js/features/roster-team-matcher.js';

registerReviewedTeams(CHASCA_REVIEWED_TEAMS);
const fallback=inferBuildProfile({name:'Chasca',element:'Anemo',weapon:'Bow',description:'On-field multi-element Nightsoul DPS'});
const profile=resolveBuildProfile({name:'Chasca',element:'Anemo'},fallback,{});
assert.equal(profile.profileSource,'reviewed');
assert.equal(profile.role,'On-field Multi-Element Main DPS / Reaction Driver');
assert.equal(profile.roleGroup,'Main DPS');
assert.equal(profile.scaling,'ATK');
assert.deepEqual(profile.tierRatings,[{label:'Main DPS',rating:'S'},{label:'Sub-DPS',rating:'—'},{label:'Support',rating:'—'},{label:'Exploration',rating:'SS'}]);
assert.deepEqual(profile.voiceActors,[{label:'EN',name:'Lauren Amante'},{label:'JP',name:'Kaida Yuhko (甲斐田裕子)'},{label:'CN',name:'Zhang Ruoyu (张若瑜)'},{label:'KR',name:'Soo-hyun (수현)'}]);
assert.equal(profile.activeVariant?.id,'obsidian-elemental-dps');
assert.deepEqual(profile.mainStats.sands,['ATK%']);
assert.equal(profile.artifactPriority[0],'Obsidian Codex');
assert.equal(profile.weaponPriority[0],"Astral Vulture's Crimson Plumage");
assert.deepEqual(profile.talentPriority,['skill','burst','attack']);
const raw=reviewedBuildProfile('Chasca');
assert.equal(raw.variants.length,2,'Chasca must retain the two meaningfully distinct current build variants');
assert.deepEqual(raw.variants.map(v=>v.id),['obsidian-elemental-dps','viridescent-swirl-driver']);
const vv=resolveBuildProfile({name:'Chasca'},fallback,{buildVariant:'viridescent-swirl-driver'});
assert.equal(vv.artifactPriority[0],'Viridescent Venerer');
assert.ok(vv.mainStats.sands.includes('Elemental Mastery'));

const sourced=recommendedTeamsForCharacter('Chasca').filter(teamHasValidSource);
const unique=new Set(sourced.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
const reviewedUnique=new Set(CHASCA_REVIEWED_TEAMS.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
assert.ok(unique.size>=30,`Chasca must expose at least 30 genuinely distinct sourced/source-informed compositions when evidence supports them; got ${unique.size}`);
assert.equal(reviewedUnique.size,CHASCA_REVIEWED_TEAMS.length,'Chasca reviewed team file must not inflate counts through duplicate member sets');
assert.ok([...reviewedUnique].every(key=>unique.has(key)),'every reviewed Chasca team must remain present in combined sourced results');
assert.ok(CHASCA_REVIEWED_TEAMS.every(team=>team.source?.url&&/^https?:\/\//.test(team.source.url)));
assert.ok(CHASCA_REVIEWED_TEAMS.every(team=>['exact','adapted'].includes(team.provenance)));
const audit=auditChascaCompatibility(RELEASED_AVATAR_AUDIT_V45);
assert.equal(audit.total,148,'Chasca compatibility audit must cover every released avatar record');
assert.ok(audit.rows.every(row=>row.status!=='invalid'));
assert.ok(audit.rows.every(row=>row.status!=='unverified'||(!row.smartTeamApproved&&!row.adaptationAllowed)));
for(const name of ['Furina','Bennett','Citlali','Mavuika','Ororon','Ineffa','Columbina','Escoffier'])assert.equal(chascaCompatibilityForCharacter(name).smartTeamApproved,true,`${name} must be source-backed for Chasca`);
assert.equal(chascaCompatibilityForCharacter('Xingqiu').adaptationAllowed,false,'Xingqiu must not be inferred as a generic Chasca Hydro substitute because coordinated attacks do not trigger');
assert.equal(chascaCompatibilityForCharacter('Candace').adaptationAllowed,false,'Candace must not be inferred as a generic Chasca Hydro substitute');
assert.equal(chascaCompatibilityForCharacter('Aether TPS').status,'not-applicable');
const ownedRoster=[{name:'Chasca',level:90,status:'Finished',priority:'High'},{name:'Furina',level:90,status:'Finished',priority:'High'},{name:'Bennett',level:90,status:'Finished',priority:'High'},{name:'Citlali',level:90,status:'Finished',priority:'High'}];
const owned=matchReviewedTeams({roster:ownedRoster,lockedNames:['Chasca'],allowUnowned:false,limit:'all'});
assert.ok(owned.results.length>0);
assert.ok(owned.results.every(team=>team.ownedComplete&&team.missing.length===0),'Owned-only must never leak an unowned teammate');
const preview=matchReviewedTeams({roster:[{name:'Chasca',level:90}],lockedNames:['Chasca'],allowUnowned:true,limit:'all'});
assert.ok(preview.results.some(team=>team.missing.length>0));
assert.match(CHASCA_COMPATIBILITY_POLICY.rule,/Every released avatar record/);
console.log(`Chasca review QA passed · ${raw.variants.length} builds · ${unique.size} distinct sourced teams · ${audit.total}/148 compatibility records checked.`);
