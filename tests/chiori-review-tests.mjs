import assert from 'node:assert/strict';
import { RELEASED_AVATAR_AUDIT_V45 } from './fixtures/released-avatar-audit-v45.mjs';
import { reviewedBuildProfile } from '../js/data/build-profiles/index.js';
import { inferBuildProfile } from '../js/features/build-engine.js';
import { resolveBuildProfile } from '../js/features/build-profiles.js';
import { CHIORI_REVIEWED_TEAMS } from '../js/data/team-profiles/chiori-reviewed.js';
import { registerReviewedTeams } from '../js/data/team-profiles/index.js';
import { recommendedTeamsForCharacter, teamHasValidSource } from '../js/data/team-recommendations.js';
import { CHIORI_COMPATIBILITY_POLICY, chioriCompatibilityForCharacter, auditChioriCompatibility } from '../js/data/character-compatibility/chiori.js';

registerReviewedTeams(CHIORI_REVIEWED_TEAMS);
const fallback=inferBuildProfile({name:'Chiori',element:'Geo',weapon:'Sword',description:'Off-field Geo damage dealer'});
const profile=resolveBuildProfile({name:'Chiori',element:'Geo'},fallback,{});
assert.equal(profile.profileSource,'reviewed');
assert.equal(profile.role,'Off-field Geo Sub-DPS / C6 On-field Geo DPS');
assert.equal(profile.roleGroup,'Sub-DPS');
assert.equal(profile.scaling,'DEF');
assert.equal(profile.activeVariant?.id,'offfield-geo-subdps');
assert.equal(profile.artifactPriority[0],'Golden Troupe');
assert.equal(profile.weaponPriority[0],'Uraku Misugiri');
const raw=reviewedBuildProfile('Chiori');
assert.equal(raw.variants.length,2);
assert.deepEqual(raw.variants.map(v=>v.id),['offfield-geo-subdps','c6-onfield-geo-dps']);
const c6=resolveBuildProfile({name:'Chiori'},fallback,{buildVariant:'c6-onfield-geo-dps'});
assert.equal(c6.roleGroup,'Main DPS');
assert.deepEqual(c6.talentPriority,['attack','skill','burst']);
const sourced=recommendedTeamsForCharacter('Chiori').filter(teamHasValidSource);
const unique=new Set(sourced.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
const reviewedUnique=new Set(CHIORI_REVIEWED_TEAMS.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
assert.ok(unique.size>=30,`Chiori should expose at least 30 distinct sourced/source-informed teams when evidence supports them; got ${unique.size}`);
assert.equal(reviewedUnique.size,CHIORI_REVIEWED_TEAMS.length,'Chiori reviewed teams must not contain duplicate member sets');
assert.ok([...reviewedUnique].every(key=>unique.has(key)));
const audit=auditChioriCompatibility(RELEASED_AVATAR_AUDIT_V45);
assert.equal(audit.total,148);
assert.ok(audit.rows.every(row=>row.status!=='invalid'));
assert.ok(audit.rows.every(row=>row.status!=='unverified'||(!row.smartTeamApproved&&!row.adaptationAllowed)));
for(const name of ['Arataki Itto','Gorou','Zhongli','Albedo','Ningguang','Navia','Furina'])assert.equal(chioriCompatibilityForCharacter(name).smartTeamApproved,true,`${name} should be approved for Chiori`);
assert.match(chioriCompatibilityForCharacter('Navia').caveat,/C0|C1/);
assert.equal(chioriCompatibilityForCharacter('Aether TPS').status,'not-applicable');
assert.match(CHIORI_COMPATIBILITY_POLICY.rule,/Every released avatar record/);
console.log(`Chiori review QA passed · ${raw.variants.length} builds · ${unique.size} distinct sourced teams · ${audit.total}/148 compatibility records checked.`);
