import assert from 'node:assert/strict';
import { RELEASED_AVATAR_AUDIT_V45 } from './fixtures/released-avatar-audit-v45.mjs';
import { reviewedBuildProfile } from '../js/data/build-profiles/index.js';
import { inferBuildProfile } from '../js/features/build-engine.js';
import { resolveBuildProfile } from '../js/features/build-profiles.js';
import { CITLALI_REVIEWED_TEAMS } from '../js/data/team-profiles/citlali-reviewed.js';
import { registerReviewedTeams } from '../js/data/team-profiles/index.js';
import { compositionKey, recommendedTeamsForCharacter, teamHasValidSource } from '../js/data/team-recommendations.js';
import { CITLALI_COMPATIBILITY_POLICY, citlaliCompatibilityForCharacter, auditCitlaliCompatibility } from '../js/data/character-compatibility/citlali.js';

registerReviewedTeams(CITLALI_REVIEWED_TEAMS);
const fallback=inferBuildProfile({name:'Citlali',element:'Cryo',weapon:'Catalyst',description:'Cryo shield and Melt Freeze support'});
const profile=resolveBuildProfile({name:'Citlali',element:'Cryo'},fallback,{});
assert.equal(profile.profileSource,'reviewed');
assert.equal(profile.role,'Cryo Shield Support / Melt-Freeze Enabler');
assert.equal(profile.roleGroup,'Support');
assert.equal(profile.scaling,'Elemental Mastery');
assert.deepEqual(profile.tierRatings,[{label:'Main DPS',rating:'—'},{label:'Sub-DPS',rating:'—'},{label:'Support',rating:'SS'},{label:'Exploration',rating:'S'}]);
assert.deepEqual(profile.voiceActors,[{label:'EN',name:'Skyler Davenport'},{label:'JP',name:'Tano Asami (田野アサミ)'},{label:'CN',name:'Liu Zhixiao (柳知萧)'},{label:'KR',name:'Lee Eun-jo (이은조)'}]);
assert.equal(profile.activeVariant?.id,'shield-buffer');
assert.equal(profile.artifactPriority[0],'Scroll of the Hero of Cinder City');
assert.equal(profile.weaponPriority[0],"Starcaller's Watch");
const raw=reviewedBuildProfile('Citlali');
assert.equal(raw.variants.length,2);
assert.deepEqual(raw.variants.map(v=>v.id),['shield-buffer','hybrid-burst-melt']);
const hybrid=resolveBuildProfile({name:'Citlali'},fallback,{buildVariant:'hybrid-burst-melt'});
assert.ok(hybrid.mainStats.goblet.includes('Cryo DMG%'));
assert.ok(hybrid.mainStats.circlet.includes('CRIT Rate'));
const sourced=recommendedTeamsForCharacter('Citlali').filter(teamHasValidSource);
const unique=new Set(sourced.map(compositionKey));
const reviewedUnique=new Set(CITLALI_REVIEWED_TEAMS.map(compositionKey));
assert.ok(unique.size>=30,`Citlali should expose at least 30 distinct sourced/source-informed teams when evidence supports them; got ${unique.size}`);
assert.equal(reviewedUnique.size,CITLALI_REVIEWED_TEAMS.length,'Citlali reviewed teams must not inflate counts through duplicate member sets');
assert.ok([...reviewedUnique].every(key=>unique.has(key)),'Every canonical Citlali reviewed composition must survive the shared recommendation registry');
const audit=auditCitlaliCompatibility(RELEASED_AVATAR_AUDIT_V45);
assert.equal(audit.total,148);
assert.ok(audit.rows.every(row=>row.status!=='invalid'));
assert.ok(audit.rows.every(row=>row.status!=='unverified'||(!row.smartTeamApproved&&!row.adaptationAllowed)));
for(const name of ['Mavuika','Arlecchino','Chasca','Bennett','Furina','Xilonen','Hu Tao','Neuvillette'])assert.equal(citlaliCompatibilityForCharacter(name).smartTeamApproved,true,`${name} should be approved for Citlali`);
assert.match(citlaliCompatibilityForCharacter('Hu Tao').caveat,/boss|Hydro/i);
assert.match(citlaliCompatibilityForCharacter('Furina').caveat,/healer/i);
assert.match(citlaliCompatibilityForCharacter('Ganyu').caveat,/does not shred Cryo RES/i);
assert.equal(citlaliCompatibilityForCharacter('Aether TPS').status,'not-applicable');
assert.match(CITLALI_COMPATIBILITY_POLICY.rule,/Every released avatar record/);
console.log(`Citlali review QA passed · ${raw.variants.length} builds · ${unique.size} distinct sourced teams · ${audit.total}/148 compatibility records checked.`);
