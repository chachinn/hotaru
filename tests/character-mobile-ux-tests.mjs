import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const css=fs.readFileSync(path.join(root,'css/character-mobile-ux.css'),'utf8');
const js=fs.readFileSync(path.join(root,'js/features/character-mobile-ux.js'),'utf8');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.match(css,/\.detail-desc\{[^}]*-webkit-line-clamp:unset!important/);
assert.match(css,/overflow:visible!important/);
assert.match(css,/\.hotaru-character-search-clear/);
assert.match(js,/aria-label','Clear character search/);
assert.match(js,/input\.value=''/);
assert.match(js,/new Event\('input',\{bubbles:true\}\)/);
assert.match(js,/focus\(\{preventScroll:true\}\)/);
assert.match(js,/MutationObserver/);
assert.match(index,/css\/character-mobile-ux\.css\?v=1\.0\.0/);
assert.match(index,/js\/features\/character-mobile-ux\.js\?v=1\.0\.0/);
console.log('Hotaru character mobile description + search clear QA passed.');
