import assert from 'node:assert/strict';
import { RELEASED_AVATAR_AUDIT_V45 } from './fixtures/released-avatar-audit-v45.mjs';
import { reviewedBuildProfile } from '../js/data/build-profiles/index.js';
import { inferBuildProfile } from '../js/features/build-engine.js';
import { resolveBuildProfile } from '../js/features/build-profiles.js';
import { CYNO_REVIEWED_TEAMS } from '../js/data/team-profiles/cyno-reviewed.js';
import { registerReviewedTeams } from '../js/data/team-profiles/index.js';
import { compositionKey, recommendedTeamsForCharacter, teamHasValidSource } from '../js/data/team-recommendations.js';
import { CYNO_COMPATIBILITY_POLICY, cynoCompatibilityForCharacter, auditCynoCompatibility } from '../js/data/character-compatibility/cyno.js';

registerReviewedTeams(CYNO_REVIEWED_TEAMS);
const fallback=inferBuildProfile({name:'Cyno',element:'Electro',weapon:'Polearm',description:'Burst-locked on-field Electro reaction DPS'});
const profile=resolveBuildProfile({name:'Cyno',element:'Electro'},fallback,{});
assert.equal(profile.profileSource,'reviewed');
assert.equal(profile.role,'On-field Electro Reaction DPS / Driver');
assert.equal(profile.roleGroup,'Main DPS');
assert.equal(profile.scaling,'Elemental Mastery');
assert.deepEqual(profile.tierRatings,[{label:'Main DPS',rating:'B'},{label:'Sub-DPS',rating:'—'},{label:'Support',rating:'—'},{label:'Exploration',rating:'C'}]);
assert.equal(profile.activeVariant?.id,'thundering-fury');
assert.equal(profile.artifactPriority[0],'Thundering Fury');
assert.equal(profile.weaponPriority[0],'Staff of the Scarlet Sands');
const raw=reviewedBuildProfile('Cyno');
assert.equal(raw.variants.length,3);
assert.deepEqual(raw.variants.map(v=>v.id),['thundering-fury','non-tf-aggravate','quickbloom-em']);
const nonTf=resolveBuildProfile({name:'Cyno'},fallback,{buildVariant:'non-tf-aggravate'});
assert.ok(nonTf.goalStats.some(x=>/180–200% solo Electro/.test(x.value)));
const qb=resolveBuildProfile({name:'Cyno'},fallback,{buildVariant:'quickbloom-em'});
assert.ok(qb.mainStats.goblet.includes('Elemental Mastery'));
assert.ok(qb.mainStats.circlet.includes('Elemental Mastery'));
const sourced=recommendedTeamsForCharacter('Cyno').filter(teamHasValidSource);
const unique=new Set(sourced.map(compositionKey));
const reviewedUnique=new Set(CYNO_REVIEWED_TEAMS.map(compositionKey));
assert.ok(unique.size>=30,`Cyno should expose at least 30 distinct sourced/source-informed teams when evidence supports them; got ${unique.size}`);
assert.equal(reviewedUnique.size,CYNO_REVIEWED_TEAMS.length,'Cyno reviewed teams must not inflate counts through duplicate member sets');
assert.ok([...reviewedUnique].every(key=>unique.has(key)),'Every canonical Cyno reviewed composition must survive the shared recommendation registry');
const audit=auditCynoCompatibility(RELEASED_AVATAR_AUDIT_V45);
assert.equal(audit.total,148);
assert.ok(audit.rows.every(row=>row.status!=='invalid'));
assert.ok(audit.rows.every(row=>row.status!=='unverified'||(!row.smartTeamApproved&&!row.adaptationAllowed)));
for(const name of ['Nahida','Baizhu','Yelan','Xingqiu','Fischl','Kuki Shinobu','Zhongli','Thoma'])assert.equal(cynoCompatibilityForCharacter(name).smartTeamApproved,true,`${name} should be approved for Cyno`);
assert.match(cynoCompatibilityForCharacter('Nahida').caveat,/wave|swap/i);
assert.match(cynoCompatibilityForCharacter('Furina').caveat,/healing|Baizhu/i);
assert.match(cynoCompatibilityForCharacter('Thoma').caveat,/Nahida|Quickburn/i);
assert.equal(cynoCompatibilityForCharacter('Aether TPS').status,'not-applicable');
assert.match(CYNO_COMPATIBILITY_POLICY.rule,/Every released avatar record/);
console.log(`Cyno review QA passed · ${raw.variants.length} builds · ${unique.size} distinct sourced teams · ${audit.total}/148 compatibility records checked.`);
