import assert from 'node:assert/strict';
import { RELEASED_AVATAR_AUDIT_V45 } from './fixtures/released-avatar-audit-v45.mjs';
import { reviewedBuildProfile } from '../js/data/build-profiles/index.js';
import { inferBuildProfile } from '../js/features/build-engine.js';
import { resolveBuildProfile } from '../js/features/build-profiles.js';
import { BAIZHU_REVIEWED_TEAMS } from '../js/data/team-profiles/baizhu-reviewed.js';
import { registerReviewedTeams } from '../js/data/team-profiles/index.js';
import { recommendedTeamsForCharacter, teamHasValidSource } from '../js/data/team-recommendations.js';
import { BAIZHU_COMPATIBILITY_POLICY, baizhuCompatibilityForCharacter, auditBaizhuCompatibility } from '../js/data/character-compatibility/baizhu.js';
import { matchReviewedTeams } from '../js/features/roster-team-matcher.js';

registerReviewedTeams(BAIZHU_REVIEWED_TEAMS);
const fallback=inferBuildProfile({name:'Baizhu',element:'Dendro',weapon:'Catalyst',description:'Dendro healer and reaction support'});
const profile=resolveBuildProfile({name:'Baizhu',element:'Dendro'},fallback,{});
assert.equal(profile.profileSource,'reviewed');
assert.equal(profile.role,'Dendro Support / Teamwide Healer / Reaction Driver');
assert.equal(profile.roleGroup,'Support');
assert.equal(profile.scaling,'HP');
assert.deepEqual(profile.tierRatings,[{label:'Main DPS',rating:'—'},{label:'Sub-DPS',rating:'—'},{label:'Support',rating:'S'},{label:'Exploration',rating:'SS'}]);
assert.deepEqual(profile.voiceActors,[{label:'EN',name:'Sean Durrie'},{label:'JP',name:'Yusa Koji (遊佐浩二)'},{label:'CN',name:'Qin Qiege (秦且歌)'},{label:'KR',name:'Lee Ho-san (이호산)'}]);
assert.equal(profile.activeVariant?.id,'dendro-support');
assert.deepEqual(profile.mainStats.sands,['Energy Recharge','HP%']);
assert.deepEqual(profile.talentPriority,['burst','skill','attack']);
assert.equal(profile.weaponPriority[0],"Jadefall's Splendor");
assert.equal(profile.artifactPriority[0],'Deepwood Memories');
const raw=reviewedBuildProfile('Baizhu');
assert.equal(raw.variants.length,3,'Baizhu must retain Dendro Support, Full Healer and Dendro Driver variants');
assert.deepEqual(raw.variants.map(v=>v.id),['dendro-support','full-healer','dendro-driver']);
const healer=resolveBuildProfile({name:'Baizhu'},fallback,{buildVariant:'full-healer'});
assert.equal(healer.artifactPriority[0],'Ocean-Hued Clam');
const driver=resolveBuildProfile({name:'Baizhu'},fallback,{buildVariant:'dendro-driver'});
assert.deepEqual(driver.mainStats.goblet,['Elemental Mastery']);
assert.ok(driver.weaponPriority.includes('Hakushin Ring'));
assert.equal(driver.reactionDriven,true);

const sourced=recommendedTeamsForCharacter('Baizhu').filter(teamHasValidSource);
const unique=new Set(sourced.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
const reviewedUnique=new Set(BAIZHU_REVIEWED_TEAMS.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
assert.ok(unique.size>=30,`Baizhu must expose at least 30 genuinely distinct sourced/source-informed compositions when evidence supports them; got ${unique.size}`);
assert.equal(reviewedUnique.size,BAIZHU_REVIEWED_TEAMS.length,'Baizhu reviewed team file must not inflate counts through duplicate member sets');
assert.ok([...reviewedUnique].every(key=>unique.has(key)),'every reviewed Baizhu team must remain present in combined sourced results');
assert.ok(BAIZHU_REVIEWED_TEAMS.every(team=>team.source?.url&&/^https?:\/\//.test(team.source.url)));
assert.ok(BAIZHU_REVIEWED_TEAMS.every(team=>['exact','adapted'].includes(team.provenance)));
const audit=auditBaizhuCompatibility(RELEASED_AVATAR_AUDIT_V45);
assert.equal(audit.total,148,'Baizhu compatibility audit must cover every released avatar record');
assert.ok(audit.rows.every(row=>row.status!=='invalid'));
assert.ok(audit.rows.every(row=>row.status!=='unverified'||(!row.smartTeamApproved&&!row.adaptationAllowed)));
for(const name of ['Nahida','Furina','Cyno','Alhaitham','Raiden Shogun','Nilou','Neuvillette','Thoma'])assert.equal(baizhuCompatibilityForCharacter(name).smartTeamApproved,true,`${name} must be source-backed for Baizhu`);
assert.equal(baizhuCompatibilityForCharacter('Aether TPS').status,'not-applicable');
const ownedRoster=[{name:'Baizhu',level:90,status:'Finished',priority:'High'},{name:'Nilou',level:90,status:'Finished',priority:'High'},{name:'Nahida',level:90,status:'Finished',priority:'High'},{name:'Neuvillette',level:90,status:'Finished',priority:'High'}];
const owned=matchReviewedTeams({roster:ownedRoster,lockedNames:['Baizhu'],allowUnowned:false,limit:'all'});
assert.ok(owned.results.length>0);
assert.ok(owned.results.every(team=>team.ownedComplete&&team.missing.length===0),'Owned-only must never leak an unowned teammate');
const preview=matchReviewedTeams({roster:[{name:'Baizhu',level:90}],lockedNames:['Baizhu'],allowUnowned:true,limit:'all'});
assert.ok(preview.results.some(team=>team.missing.length>0));
assert.match(BAIZHU_COMPATIBILITY_POLICY.rule,/Every released avatar record/);
console.log(`Baizhu review QA passed · ${raw.variants.length} builds · ${unique.size} distinct sourced teams · ${audit.total}/148 compatibility records checked.`);
