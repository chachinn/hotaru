import assert from 'node:assert/strict';
import { RELEASED_AVATAR_AUDIT_V45 } from './fixtures/released-avatar-audit-v45.mjs';
import { reviewedBuildProfile } from '../js/data/build-profiles/index.js';
import { inferBuildProfile } from '../js/features/build-engine.js';
import { resolveBuildProfile } from '../js/features/build-profiles.js';
import { DEHYA_REVIEWED_TEAMS } from '../js/data/team-profiles/dehya-reviewed.js';
import { registerReviewedTeams } from '../js/data/team-profiles/index.js';
import { compositionKey, recommendedTeamsForCharacter, teamHasValidSource } from '../js/data/team-recommendations.js';
import { DEHYA_COMPATIBILITY_POLICY, dehyaCompatibilityForCharacter, auditDehyaCompatibility } from '../js/data/character-compatibility/dehya.js';

registerReviewedTeams(DEHYA_REVIEWED_TEAMS);
const fallback=inferBuildProfile({name:'Dehya',element:'Pyro',weapon:'Claymore',description:'Pyro damage mitigation support and Burst DPS'});
const profile=resolveBuildProfile({name:'Dehya',element:'Pyro'},fallback,{});
assert.equal(profile.profileSource,'reviewed');
assert.equal(profile.role,'Pyro Support / Burgeon Trigger / On-field Burst DPS');
assert.equal(profile.roleGroup,'Support');
assert.deepEqual(profile.tierRatings,[{label:'Main DPS',rating:'D'},{label:'Sub-DPS',rating:'C'},{label:'Support',rating:'B'},{label:'Exploration',rating:'A'}]);
assert.deepEqual(profile.voiceActors,[{label:'EN',name:'Amber May'},{label:'JP',name:'Fukuhara Ayaka (福原綾香)'},{label:'CN',name:'Chen Yu (陈雨)'},{label:'KR',name:'Kim Hyeon-sim (김현심)'}]);
assert.equal(profile.activeVariant?.id,'off-field-support');
const raw=reviewedBuildProfile('Dehya');
assert.equal(raw.variants.length,4);
assert.deepEqual(raw.variants.map(v=>v.id),['off-field-support','burgeon','on-field-burst','nod-krai-overvape']);
const burgeon=resolveBuildProfile({name:'Dehya'},fallback,{buildVariant:'burgeon'});
assert.deepEqual(burgeon.mainStats.sands,['Elemental Mastery']);
assert.ok(burgeon.goalStats.some(x=>/No ER requirement/.test(x.value)));
const dps=resolveBuildProfile({name:'Dehya'},fallback,{buildVariant:'on-field-burst'});
assert.ok(dps.goalStats.some(x=>/160–210%/.test(x.value)));
const nod=resolveBuildProfile({name:'Dehya'},fallback,{buildVariant:'nod-krai-overvape'});
assert.equal(nod.artifactPriority[0],'Night of the Sky’s Unveiling');
assert.ok(nod.goalStats.some(x=>/Ineffa \+ Aino/.test(x.value)));
const sourced=recommendedTeamsForCharacter('Dehya').filter(teamHasValidSource);
const unique=new Set(sourced.map(compositionKey));
const reviewedUnique=new Set(DEHYA_REVIEWED_TEAMS.map(compositionKey));
assert.ok(unique.size>=30,`Dehya should expose at least 30 distinct sourced/source-informed teams when evidence supports them; got ${unique.size}`);
assert.equal(reviewedUnique.size,DEHYA_REVIEWED_TEAMS.length,'Dehya reviewed teams must not inflate counts through duplicate member sets');
assert.ok([...reviewedUnique].every(key=>unique.has(key)),'Every canonical Dehya reviewed composition must survive the shared recommendation registry');
const audit=auditDehyaCompatibility(RELEASED_AVATAR_AUDIT_V45);
assert.equal(audit.total,148);
assert.ok(audit.rows.every(row=>row.status!=='invalid'));
assert.ok(audit.rows.every(row=>row.status!=='unverified'||(!row.smartTeamApproved&&!row.adaptationAllowed)));
for(const name of ['Furina','Bennett','Emilie','Ganyu','Mualani','Ineffa','Aino','Nahida','Kuki Shinobu'])assert.equal(dehyaCompatibilityForCharacter(name).smartTeamApproved,true,`${name} should be approved for Dehya`);
assert.match(dehyaCompatibilityForCharacter('Xingqiu').caveat,/Burst does not trigger|off-field|Burgeon/i);
assert.match(dehyaCompatibilityForCharacter('Aino').caveat,/Ineffa|Night of the Sky/i);
assert.match(dehyaCompatibilityForCharacter('Mualani').caveat,/Emilie|Nahida/i);
assert.equal(dehyaCompatibilityForCharacter('Aether TPS').status,'not-applicable');
assert.match(DEHYA_COMPATIBILITY_POLICY.rule,/Every released avatar record/);
console.log(`Dehya review QA passed · ${raw.variants.length} builds · ${unique.size} distinct sourced teams · ${audit.total}/148 compatibility records checked.`);
