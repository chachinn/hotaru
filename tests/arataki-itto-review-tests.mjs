import assert from 'node:assert/strict';
import { RELEASED_AVATAR_AUDIT_V45 } from './fixtures/released-avatar-audit-v45.mjs';
import { reviewedBuildProfile } from '../js/data/build-profiles/index.js';
import { inferBuildProfile } from '../js/features/build-engine.js';
import { resolveBuildProfile } from '../js/features/build-profiles.js';
import { ARATAKI_ITTO_REVIEWED_TEAMS } from '../js/data/team-profiles/arataki-itto-reviewed.js';
import { registerReviewedTeams } from '../js/data/team-profiles/index.js';
import { recommendedTeamsForCharacter, teamHasValidSource } from '../js/data/team-recommendations.js';
import { ARATAKI_ITTO_COMPATIBILITY_POLICY, aratakiIttoCompatibilityForCharacter, auditAratakiIttoCompatibility } from '../js/data/character-compatibility/arataki-itto.js';
import { matchReviewedTeams } from '../js/features/roster-team-matcher.js';

registerReviewedTeams(ARATAKI_ITTO_REVIEWED_TEAMS);
const fallback=inferBuildProfile({name:'Arataki Itto',element:'Geo',weapon:'Claymore',description:'DEF-scaling on-field Geo DPS'});
const profile=resolveBuildProfile({name:'Arataki Itto',element:'Geo'},fallback,{});
assert.equal(profile.profileSource,'reviewed');
assert.equal(profile.role,'On-Field Geo DPS');
assert.equal(profile.roleGroup,'Main DPS');
assert.equal(profile.scaling,'DEF');
assert.deepEqual(profile.tierRatings,[{label:'Main DPS',rating:'B'},{label:'Sub-DPS',rating:'—'},{label:'Support',rating:'—'},{label:'Exploration',rating:'B'}]);
assert.deepEqual(profile.voiceActors,[{label:'EN',name:'Max Mittelman'},{label:'JP',name:'Nishikawa Takanori (西川 貴教)'},{label:'CN',name:'Liu Zhaokun (刘照坤)'},{label:'KR',name:'Song Jun-seok (송준석)'}]);
assert.equal(profile.activeVariant?.id,'standard-kesagiri');
assert.deepEqual(profile.mainStats.sands,['DEF%']);
assert.deepEqual(profile.mainStats.goblet,['Geo DMG%','DEF%']);
assert.deepEqual(profile.talentPriority,['attack','burst','skill']);
assert.equal(profile.weaponPriority[0],'Redhorn Stonethresher');
assert.equal(profile.artifactPriority[0],'Husk of Opulent Dreams');
const raw=reviewedBuildProfile('Itto');
assert.equal(raw.variants.length,2,'Itto must retain Standard Kesagiri and the genuinely distinct Xianyun Plunge build');
assert.deepEqual(raw.variants.map(v=>v.id),['standard-kesagiri','xianyun-plunge']);
const plunge=resolveBuildProfile({name:'Arataki Itto'},fallback,{buildVariant:'xianyun-plunge'});
assert.ok(plunge.weaponPriority.includes('Fruitful Hook'),'Xianyun Plunge build must retain its plunge-specific weapon option');
assert.match(plunge.activeVariant.note,/Plung/i);

const sourced=recommendedTeamsForCharacter('Arataki Itto').filter(teamHasValidSource);
const unique=new Set(sourced.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
const reviewedUnique=new Set(ARATAKI_ITTO_REVIEWED_TEAMS.map(team=>[...new Set((team.members||[]).map(name=>String(name).toLowerCase()))].sort().join('|')));
assert.ok(unique.size>=30,`Itto must expose at least 30 genuinely distinct sourced/source-informed compositions when evidence supports them; got ${unique.size}`);
assert.equal(reviewedUnique.size,ARATAKI_ITTO_REVIEWED_TEAMS.length,'Itto reviewed team file must not inflate counts through duplicate member sets');
assert.ok([...reviewedUnique].every(key=>unique.has(key)),'every reviewed Itto team must remain present in combined sourced results');
assert.ok(ARATAKI_ITTO_REVIEWED_TEAMS.every(team=>team.source?.url&&/^https?:\/\//.test(team.source.url)));
assert.ok(ARATAKI_ITTO_REVIEWED_TEAMS.every(team=>['exact','adapted'].includes(team.provenance)));
const audit=auditAratakiIttoCompatibility(RELEASED_AVATAR_AUDIT_V45);
assert.equal(audit.total,148,'Itto compatibility audit must cover every released avatar record');
assert.ok(audit.rows.every(row=>row.status!=='invalid'));
assert.ok(audit.rows.every(row=>row.status!=='unverified'||(!row.smartTeamApproved&&!row.adaptationAllowed)));
for(const name of ['Gorou','Xilonen','Chiori','Albedo','Zhongli','Furina','Xianyun'])assert.equal(aratakiIttoCompatibilityForCharacter(name).smartTeamApproved,true,`${name} must be source-backed for Itto`);
assert.equal(aratakiIttoCompatibilityForCharacter('Aether TPS').status,'not-applicable');
const ownedRoster=[{name:'Arataki Itto',level:90,status:'Finished',priority:'High'},{name:'Chiori',level:90,status:'Finished',priority:'High'},{name:'Gorou',level:90,status:'Finished',priority:'High'},{name:'Zhongli',level:90,status:'Finished',priority:'High'}];
const owned=matchReviewedTeams({roster:ownedRoster,lockedNames:['Arataki Itto'],allowUnowned:false,limit:'all'});
assert.ok(owned.results.length>0);
assert.ok(owned.results.every(team=>team.ownedComplete&&team.missing.length===0),'Owned-only must never leak an unowned teammate');
const preview=matchReviewedTeams({roster:[{name:'Arataki Itto',level:90}],lockedNames:['Arataki Itto'],allowUnowned:true,limit:'all'});
assert.ok(preview.results.some(team=>team.missing.length>0));
assert.match(ARATAKI_ITTO_COMPATIBILITY_POLICY.rule,/Every released avatar record/);
console.log(`Arataki Itto review QA passed · ${raw.variants.length} builds · ${unique.size} distinct sourced teams · ${audit.total}/148 compatibility records checked.`);
